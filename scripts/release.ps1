param(
    [Parameter(Mandatory=$true)]
    [string]$Version
)

$ErrorActionPreference = "Stop"
$ProjectRoot = Split-Path -Parent $PSScriptRoot
Set-Location $ProjectRoot

# Check if gh is installed
if (!(Get-Command gh -ErrorAction SilentlyContinue)) {
    Write-Error "GitHub CLI (gh) is not installed. Install it from https://cli.github.com/"
    exit 1
}

# Check if gh is authenticated
gh auth status 2>&1 | Out-Null
if ($LASTEXITCODE -ne 0) {
    Write-Error "Not authenticated with gh. Run 'gh auth login' first."
    exit 1
}

$Tag = "v$Version"

# 1. Set version in package.json
$pkg = Get-Content package.json -Raw | ConvertFrom-Json
$pkg.version = $Version
$pkg | ConvertTo-Json -Depth 10 | Set-Content package.json
Write-Output "OK: package.json version set to $Version"

# 2. Commit and Tag
git add package.json scripts/release.ps1 .github/workflows/build.yml
git commit -m "$Tag"
git push origin main
$LASTEXITCODE = 0
git tag -f "$Tag"
git push origin "$Tag" --force
Write-Output "OK: Pushed tag $Tag to crux-client"

# 3. Create release on crux-client (triggers GitHub Action)
gh release create "$Tag" --title "$Tag" --notes "Crux Client $Tag" -R "Dev-Reds/crux-client"
Write-Output "OK: Release $Tag created on crux-client (build + upload will run automatically)"

# 4. Wait for GitHub Action to complete and upload all artifacts
Write-Output "OK: Waiting for GitHub Action to build and upload all installer formats..."
$maxWait = 600  # 10 minutes max
$waited = 0
$interval = 30
while ($waited -lt $maxWait) {
    $release = gh release view "$Tag" -R "Dev-Reds/crux-client" --json assets 2>$null
    if ($release) {
        $assets = $release | ConvertFrom-Json
        $assetNames = $assets.assets | Select-Object -ExpandProperty name
        # Check for all expected formats
        $hasExe = $assetNames | Where-Object { $_ -like "*.exe" }
        $hasZip = $assetNames | Where-Object { $_ -like "*.zip" }
        $hasTarGz = $assetNames | Where-Object { $_ -like "*.tar.gz" }
        $hasDmg = $assetNames | Where-Object { $_ -like "*.dmg" }
        $hasAppImage = $assetNames | Where-Object { $_ -like "*.AppImage" }
        $hasDeb = $assetNames | Where-Object { $_ -like "*.deb" }
        $hasRpm = $assetNames | Where-Object { $_ -like "*.rpm" }
        
        if ($hasExe -and $hasZip -and $hasTarGz -and $hasDmg -and $hasAppImage -and $hasDeb -and $hasRpm) {
            Write-Output "OK: All installer formats uploaded by GitHub Action"
            break
        }
    }
    Start-Sleep $interval
    $waited += $interval
    Write-Output ("  Still waiting... " + $waited + "s / " + $maxWait + "s")
}

# 5. Build crux_code.zip locally
Write-Output "OK: Building crux_code.zip..."
$zipPath = Join-Path $env:USERPROFILE "Downloads\crux_code.zip"
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }

# Zip all files except node_modules and .git
$compress = @{
    Path = (Get-ChildItem -Path $ProjectRoot -Exclude "node_modules", ".git" | Select-Object -ExpandProperty FullName)
    DestinationPath = $zipPath
    CompressionLevel = "Optimal"
}
Compress-Archive @compress -Force
Write-Output "OK: crux_code.zip created at: $zipPath"

# 6. Upload zip to crux-code release
Write-Output ("OK: Uploading crux_code.zip to crux-code release " + $Tag + "...")
gh release upload "$Tag" "$zipPath" --clobber -R "Dev-Reds/crux-code" 2>&1 | Out-Null
if ($LASTEXITCODE -ne 0) {
    gh release create "$Tag" "$zipPath" --title "Crux Code $Tag" --notes "Autogenerated source zip" -R "Dev-Reds/crux-code"
    Write-Output "OK: Release $Tag created on crux-code and zip uploaded"
} else {
    Write-Output "OK: crux_code.zip uploaded to existing release $Tag on crux-code"
}

Write-Output "`nDone!"
Write-Output ("  Installer: https://github.com/Dev-Reds/crux-client/releases/tag/" + $Tag)
Write-Output ("  Zip:       https://github.com/Dev-Reds/crux-code/releases/latest/download/crux_code.zip")
Write-Output ""
Write-Output "Available formats on release:"
Write-Output "  Windows:    NSIS Installer (.exe), Portable (.zip)"
Write-Output "  Linux:      AppImage, .deb, .rpm, .zip, .tar.gz"
Write-Output "  macOS:      .dmg, .zip"
